import type { IncomingMessage, ServerResponse } from "node:http";
import { brotliCompressSync, constants as zlib, gzipSync } from "node:zlib";
import { defineConfig } from "@rspack/cli";
import { type Compiler, rspack } from "@rspack/core";
import { ReactRefreshRspackPlugin } from "@rspack/plugin-react-refresh";
import {
  analyze,
  analyzeDir,
  buildFlags,
  CLIENT_DEV_PORT,
  clientPublicPath,
  isDev,
  paths,
  resolve,
  rootDir,
  SSR_PORT,
  swcRule,
} from "./rspack.shared.ts";

export const ASSET_MANIFEST = "asset-manifest.json";

/** Lazy route chunks are named `route-<name>` by the imports in src/app/routes.tsx. */
const ROUTE_CHUNK_PREFIX = "route-";
/** Chunks every page needs right after hydration: fetched early, run late. */
const PRELOADED_CHUNKS = ["realtime"];

/**
 * Emits `asset-manifest.json` describing the initial JS/CSS for the `main` entry, plus
 * the scripts each lazy route adds and the chunks worth preloading. The SSR server reads it to emit <script>/<link> tags
 * with content-hashed names, so HTML never has to be generated by the bundler (the server
 * owns the document), and a page's own chunk is requested with the page rather than
 * after the main bundle has run.
 */
class AssetManifestPlugin {
  apply(compiler: Compiler) {
    const { RawSource } = compiler.webpack.sources;
    compiler.hooks.thisCompilation.tap("AssetManifestPlugin", (compilation) => {
      compilation.hooks.processAssets.tap(
        { name: "AssetManifestPlugin", stage: rspack.Compilation.PROCESS_ASSETS_STAGE_REPORT },
        () => {
          const entry = compilation.entrypoints.get("main");
          if (!entry) return;
          const files = entry.getFiles().filter((file) => !file.includes(".hot-update."));
          const publicPath = String(compilation.outputOptions.publicPath ?? "/");
          const initial = new Set(files);
          const routes: Record<string, string[]> = {};
          const preload: string[] = [];
          for (const [name, group] of compilation.namedChunkGroups) {
            const scripts = group
              .getFiles()
              .filter((f) => f.endsWith(".js") && !initial.has(f) && !f.includes(".hot-update."))
              .map((f) => publicPath + f);
            if (name.startsWith(ROUTE_CHUNK_PREFIX))
              routes[name.slice(ROUTE_CHUNK_PREFIX.length)] = scripts;
            else if (PRELOADED_CHUNKS.includes(name)) preload.push(...scripts);
          }
          const manifest = {
            scripts: files.filter((f) => f.endsWith(".js")).map((f) => publicPath + f),
            styles: files.filter((f) => f.endsWith(".css")).map((f) => publicPath + f),
            routes,
            preload,
          };
          compilation.emitAsset(ASSET_MANIFEST, new RawSource(JSON.stringify(manifest, null, 2)));
        },
      );
    });
  }
}

/**
 * Writes a Brotli and a gzip copy next to every text asset (`main.abc.js.br`, `.gz`).
 * The server picks one by the request's Accept-Encoding, so nothing is compressed per
 * request and the slow, best-ratio settings cost only build time. Source maps are left
 * alone: only developers' tools fetch them.
 */
class PrecompressPlugin {
  apply(compiler: Compiler) {
    const { RawSource } = compiler.webpack.sources;
    compiler.hooks.thisCompilation.tap("PrecompressPlugin", (compilation) => {
      compilation.hooks.processAssets.tap(
        {
          name: "PrecompressPlugin",
          stage: rspack.Compilation.PROCESS_ASSETS_STAGE_OPTIMIZE_TRANSFER,
        },
        () => {
          for (const { name, source } of compilation.getAssets()) {
            if (!/\.(js|css|svg|json)$/.test(name)) continue;
            const content = source.buffer();
            // Tiny files don't get smaller, and each variant is one more file to list.
            if (content.length < 1_024) continue;
            compilation.emitAsset(
              `${name}.br`,
              new RawSource(
                brotliCompressSync(content, {
                  params: { [zlib.BROTLI_PARAM_QUALITY]: zlib.BROTLI_MAX_QUALITY },
                }),
              ),
            );
            compilation.emitAsset(`${name}.gz`, new RawSource(gzipSync(content, { level: 9 })));
          }
        },
      );
    });
  }
}

/**
 * Bundle analysis (`pnpm analyze`): which modules are in which chunk, why, and what is
 * duplicated. Loaded only on request, so a normal build doesn't pay for it. The report is
 * a static HTML file; nothing is served or opened.
 */
const rsdoctor = analyze
  ? new (await import("@rsdoctor/rspack-plugin")).RsdoctorRspackPlugin({
      disableClientServer: true,
      output: { mode: "brief", reportDir: analyzeDir, options: { type: ["html"] } },
    })
  : null;

export default defineConfig({
  name: "client",
  context: rootDir,
  mode: isDev ? "development" : "production",
  target: "browserslist",
  entry: { main: paths.clientEntry },
  output: {
    path: paths.clientOutput,
    publicPath: clientPublicPath,
    filename: isDev ? "js/[name].js" : "js/[name].[contenthash:8].js",
    chunkFilename: isDev ? "js/[name].chunk.js" : "js/[name].[contenthash:8].chunk.js",
    cssFilename: isDev ? "css/[name].css" : "css/[name].[contenthash:8].css",
    cssChunkFilename: isDev ? "css/[name].chunk.css" : "css/[name].[contenthash:8].chunk.css",
    assetModuleFilename: "media/[name].[contenthash:8][ext]",
    clean: true,
  },
  resolve,
  devtool: isDev ? "cheap-module-source-map" : "source-map",
  module: {
    rules: [
      swcRule({ target: "web", refresh: isDev }),
      {
        test: /\.css$/,
        type: "css",
        use: [
          {
            loader: "postcss-loader",
            options: { postcssOptions: { plugins: ["@tailwindcss/postcss"] } },
          },
        ],
      },
      { test: /\.(woff2?|png|svg|ico)$/, type: "asset/resource" },
    ],
  },
  plugins: [
    new rspack.DefinePlugin(buildFlags),
    new AssetManifestPlugin(),
    !isDev && new PrecompressPlugin(),
    isDev && new ReactRefreshRspackPlugin(),
    rsdoctor,
  ],
  optimization: {
    // Stable vendor chunk: React/Router change far less often than app code, so it
    // stays cached across deploys.
    splitChunks: {
      chunks: "all",
      cacheGroups: {
        framework: {
          test: /[\\/]node_modules[\\/](react|react-dom|scheduler|react-router)[\\/]/,
          name: "framework",
          priority: 20,
        },
      },
    },
    runtimeChunk: "single",
  },
  performance: {
    hints: isDev ? false : "warning",
    maxEntrypointSize: 350_000,
    maxAssetSize: 300_000,
  },
  devServer: {
    port: CLIENT_DEV_PORT,
    hot: true,
    // HTML is served by the SSR server on a different port.
    headers: { "Access-Control-Allow-Origin": "*" },
    allowedHosts: "all",
    client: { overlay: { errors: true, warnings: false } },
    // Everything, including asset-manifest.json, is served from memory; the SSR server
    // fetches the manifest from here over HTTP (see server/manifest.ts).
    // This server only serves assets. If someone opens it in a browser, send page
    // requests to the SSR server instead of showing "Cannot GET /".
    setupMiddlewares: (middlewares) => {
      middlewares.push({
        name: "redirect-pages-to-ssr",
        middleware: (req: IncomingMessage, res: ServerResponse, next: () => void) => {
          if (req.method !== "GET" || !req.headers.accept?.includes("text/html")) return next();
          res.writeHead(302, { Location: `http://localhost:${SSR_PORT}${req.url ?? "/"}` });
          res.end();
        },
      });
      return middlewares;
    },
  },
});
